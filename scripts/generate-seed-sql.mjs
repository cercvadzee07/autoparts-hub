// Builds supabase/seed.sql from src/lib/data/seed.ts (the same data the demo mode uses).
// Run: npm run seed:sql   (Node 22.18+ / 24 — uses built-in TypeScript type stripping)
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  SEED_CATEGORIES,
  SEED_GENERATIONS,
  SEED_MAKES,
  SEED_MODELS,
  SEED_PRODUCTS,
  SEED_STORE,
} from "../src/lib/data/seed.ts";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const lines = [];
const push = (s) => lines.push(s);

push("-- Generated by scripts/generate-seed-sql.mjs — do not edit by hand.");
push("begin;");
push(
  `insert into public.stores (id, slug, name, phone, city) values (${q(SEED_STORE.id)}, ${q(SEED_STORE.slug)}, ${q(SEED_STORE.name)}, ${q(SEED_STORE.phone)}, ${q(SEED_STORE.city)}) on conflict (id) do nothing;`,
);
for (const c of SEED_CATEGORIES) {
  push(
    `insert into public.categories (id, slug, name_ka, name_en, name_ru, icon, sort_order) values (${q(c.id)}, ${q(c.slug)}, ${q(c.name.ka)}, ${q(c.name.en)}, ${q(c.name.ru)}, ${q(c.icon)}, ${c.sortOrder}) on conflict (id) do nothing;`,
  );
}
for (const m of SEED_MAKES) {
  push(`insert into public.vehicle_makes (id, slug, name) values (${q(m.id)}, ${q(m.slug)}, ${q(m.name)}) on conflict (id) do nothing;`);
}
for (const m of SEED_MODELS) {
  push(
    `insert into public.vehicle_models (id, make_id, slug, name) values (${q(m.id)}, ${q(m.makeId)}, ${q(m.slug)}, ${q(m.name)}) on conflict (id) do nothing;`,
  );
}
for (const g of SEED_GENERATIONS) {
  push(
    `insert into public.vehicle_generations (id, model_id, slug, name, code, year_from, year_to) values (${q(g.id)}, ${q(g.modelId)}, ${q(g.slug)}, ${q(g.name)}, ${q(g.code)}, ${g.yearFrom}, ${g.yearTo ?? "null"}) on conflict (id) do nothing;`,
  );
}
for (const p of SEED_PRODUCTS) {
  push(
    `insert into public.products (id, store_id, inventory_code, slug, title_ka, title_en, title_ru, description_ka, description_en, description_ru, category_id, condition, status, price, quantity, oem_number, featured, created_at, updated_at) values (${[
      q(p.id), q(p.storeId), q(p.inventoryCode), q(p.slug), q(p.title.ka), q(p.title.en), q(p.title.ru),
      q(p.description.ka), q(p.description.en), q(p.description.ru), q(p.categoryId), q(p.condition), q(p.status),
      p.price, p.quantity, q(p.oemNumber), p.featured, q(p.createdAt), q(p.createdAt),
    ].join(", ")}) on conflict (id) do nothing;`,
  );
  push(
    `insert into public.product_images (product_id, url, sort_order) select ${q(p.id)}, ${q(p.image)}, 0 where not exists (select 1 from public.product_images where product_id = ${q(p.id)});`,
  );
  for (const c of p.compatibility) {
    push(
      `insert into public.product_compatibility (product_id, generation_id, year_from, year_to) values (${q(p.id)}, ${q(c.generationId)}, ${c.yearFrom}, ${c.yearTo}) on conflict do nothing;`,
    );
  }
}
push(
  `insert into public.store_counters (store_id, inventory_seq) values (${q(SEED_STORE.id)}, ${SEED_PRODUCTS.length}) on conflict (store_id) do update set inventory_seq = greatest(store_counters.inventory_seq, excluded.inventory_seq);`,
);
push("commit;");

const file = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(file, lines.join("\n") + "\n");
console.log(`Wrote ${SEED_PRODUCTS.length} products to ${file}`);
